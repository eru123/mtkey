// Computes the Blowfish P-array and S-boxes from the hex expansion of pi's
// fractional part, the way the original reference tables were produced.
// Run: node scripts/gen-blowfish-tables.mjs
//
// The first words are the well-known Blowfish constants (0x243F6A88,
// 0x85A308D3, ...) so a mismatch would be caught immediately; the real
// gate is the mcrypt cross-language vector suite (real PHP 5.6 blowfish).
import { writeFileSync } from 'node:fs'

const WORDS = 18 + 4 * 256 // 1042 32-bit words = 8336 hex digits

// pi * 16^extra, computed with Machin's formula:
// pi/4 = 4*arctan(1/5) - arctan(1/239), arctan(1/x) via the alternating series.
function arctanInv(x, one) {
  const x2 = x * x
  let term = one / x
  let sum = 0n
  let k = 0n
  while (term !== 0n) {
    const add = k % 2n === 0n ? term : -term
    sum += add / (2n * k + 1n)
    term /= x2
    k += 1n
  }
  return sum
}

const GUARD_HEX = 40 // extra digits of headroom to absorb rounding error
const scale = 16n ** BigInt(WORDS * 8 + GUARD_HEX)
// unit = 1 scaled to our fixed point; Machin: pi = 16*atan(1/5) - 4*atan(1/239)
const pi = 16n * arctanInv(5n, scale) - 4n * arctanInv(239n, scale)

// Fractional part only, as hex digits.
const frac = (pi % scale).toString(16).padStart(WORDS * 8 + GUARD_HEX, '0')
const digits = frac.slice(0, WORDS * 8).padEnd(WORDS * 8, '0')

const words = []
for (let i = 0; i < WORDS; i++) words.push('0x' + digits.slice(i * 8, i * 8 + 8).toUpperCase())

const KNOWN_FIRST = [
  '0x243F6A88', '0x85A308D3', '0x13198A2E', '0x03707344',
  '0xA4093822', '0x299F31D0', '0x082EFA98', '0xEC4E6C89',
]
for (let i = 0; i < KNOWN_FIRST.length; i++) {
  if (words[i] !== KNOWN_FIRST[i]) {
    console.error(`pi hex digit check failed at word ${i}: ${words[i]} != ${KNOWN_FIRST[i]}`)
    process.exit(1)
  }
}

const p = words.slice(0, 18)
const s = [words.slice(18, 18 + 256), words.slice(18 + 256, 18 + 512), words.slice(18 + 512, 18 + 768), words.slice(18 + 768, 18 + 1024)]

const body = `/** Blowfish initial P-array and S-boxes: the hex expansion of the
 * fractional part of pi, exactly as in the reference implementation.
 * Generated by scripts/gen-blowfish-tables.mjs (BigInt Machin formula) and
 * pinned by the first eight words plus the mcrypt cross-language vectors;
 * do not edit by hand. */

export const P_INIT: readonly number[] = [
  ${p.join(', ')}
]

export const S_INIT: readonly (readonly number[])[] = [
  [${s[0].join(', ')}],
  [${s[1].join(', ')}],
  [${s[2].join(', ')}],
  [${s[3].join(', ')}],
]
`

writeFileSync(new URL('../src/core/blowfish-tables.ts', import.meta.url), body)
console.log('wrote src/core/blowfish-tables.ts with', WORDS, 'words; first word', words[0], 'last word', words[WORDS - 1])
